process.env.NODE_ENV = 'production';
process.env.JWT_ACCESS_SECRET = 'test-access-secret-only-at-least-32-characters';
process.env.JWT_REFRESH_SECRET = 'test-refresh-secret-only-at-least-32-characters';
process.env.CORS_ORIGIN = 'https://frontend.example.com';
process.env.BCRYPT_SALT_ROUNDS = '4';
const {test, after} = require('node:test');
const assert = require('node:assert/strict');
const request = require('supertest');
const {randomUUID} = require('crypto');
if(!process.env.DATABASE_URL?.includes('scribeboard_test'))throw Error('Use a disposable scribeboard_test database');
const app = require('../src/app');
const {prisma} = require('../src/config/database');
const email = `cookie-${randomUUID()}@example.com`;
let userId;
const browser = (path, cookie) => { const req = request(app).post('/api/v1/auth/'+path).set('Origin',process.env.CORS_ORIGIN).set('X-Scribe-Session','cookie'); return cookie ? req.set('Cookie',cookie) : req; };
const pair = r => r.headers['set-cookie'][0].split(';')[0];
after(async()=>{if(userId)await prisma.user.delete({where:{id:userId}});await prisma.$disconnect();});
test('cookie sessions restore roles, rotate tokens, reject CSRF, and revoke on logout',async()=>{
 const signup = await browser('register').send({email,password:'CookieTest123',firstName:'Cookie',lastName:'Test'});
 assert.equal(signup.status,201);userId=signup.body.data.user.id;
 assert.equal(signup.body.data.refreshToken,undefined);
 const header=signup.headers['set-cookie'][0];for(const attribute of ['HttpOnly','Secure','SameSite=None','Partitioned','Path=/api/v1/auth','Expires='])assert.ok(header.includes(attribute),attribute);
 const cookie=pair(signup);
 const hostile=await request(app).post('/api/v1/auth/refresh-tokens').set('Origin','https://attacker.example').set('X-Scribe-Session','cookie').set('Cookie',cookie).send({});assert.equal(hostile.status,403);
 const noHeader=await request(app).post('/api/v1/auth/refresh-tokens').set('Cookie',cookie).send({});assert.equal(noHeader.status,400);
 const noOrigin=await request(app).post('/api/v1/auth/refresh-tokens').set('X-Scribe-Session','cookie').set('Cookie',cookie).send({});assert.equal(noOrigin.status,403);
 await prisma.user.update({where:{id:userId},data:{role:'ADMIN'}});
 const refresh=await browser('refresh-tokens',cookie).send({});assert.equal(refresh.status,200);assert.equal(refresh.body.data.refreshToken,undefined);assert.notEqual(pair(refresh),cookie);
 const profile=await request(app).get('/api/v1/auth/profile').set('Authorization','Bearer '+refresh.body.data.accessToken);assert.equal(profile.body.data.role,'ADMIN');
 assert.equal((await browser('refresh-tokens',cookie).send({})).status,401);
 const logout=await browser('logout',pair(refresh)).send({});assert.equal(logout.status,200);assert.match(logout.headers['set-cookie'][0],/Expires=Thu, 01 Jan 1970/);
 assert.equal((await browser('refresh-tokens',pair(refresh)).send({})).status,401);
 assert.equal((await request(app).get('/api/v1/auth/profile').set('Authorization','Bearer '+refresh.body.data.accessToken)).status,401);
});
